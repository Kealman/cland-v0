// Web: authenticated HTTP uploads through the production composer in isolated Headless Shell.
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { resizePage, webFixture } from './harness.ts';
import { sessionUi } from '../../hub/test/session-credential-fixture.ts';
import type { TopicMessage } from '../../shared/wire/index.ts';

test('composer sends one PNG with its caption and refuses oversized files while retaining native keys and artifact chips', async t => {
  const fixture = await webFixture(t, { prepare: async root => {
    await mkdir(join(root, '.cland'), { recursive: true });
    await writeFile(join(root, '.cland/config.toml'), '[artifacts]\nmax_upload_mb = 1\n');
  } });
  const ui = await sessionUi(t, fixture.hub.discovery);
  await fixture.pageCase(t, async page => {
    await page.getByRole('button', { name: 'Topics', exact: true }).click();
    await page.locator('[data-object-id="general"]').click();
    const form = page.getByRole('form', { name: 'Composer', exact: true });
    const input = form.locator('input[type=file]');
    const picker = page.waitForEvent('filechooser');
    await form.getByRole('button', { name: 'Attach a file', exact: true }).click();
    await (await picker).setFiles({ name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jKXkAAAAASUVORK5CYII=', 'base64') });
    await form.locator('[data-composer-file]').waitFor();
    const field = form.getByRole('textbox', { name: 'Message text' });
    await field.pressSequentially('PNG caption');
    const receipt = page.waitForResponse(response => response.url().endsWith('/upload') && response.request().method() === 'POST');
    await field.press('Enter');
    const response = await receipt;
    const result = await response.json();
    assert.equal(result.ok, true, JSON.stringify(result));
    await page.locator(`[data-message-id="${result.value.message.id}"]`).waitFor();
    const history = await ui.request({ type: 'topic.history', topic: 'general' });
    const messages = (history.value as { messages: TopicMessage[] }).messages;
    assert.equal(messages.length, 1);
    assert.equal(messages[0]!.text, 'PNG caption');
    assert.equal(messages[0]!.fromKind, 'human');
    assert.deepEqual(messages[0]!.artifacts?.map(row => row.title), ['pixel.png']);
    assert.ok(messages.every(row => !row.text.startsWith('▣')));
    await input.setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(1024 * 1024 + 1) });
    const refused = form.locator('[data-composer-file][data-refused="true"]');
    await refused.waitFor();
    assert.match(await refused.getAttribute('title') ?? '', /1 MiB/);
    await field.pressSequentially('s~@');
    assert.equal(await field.inputValue(), 's~@');
    assert.equal(await form.getByRole('button', { name: 'Send', exact: true }).isDisabled(), true);
    await form.getByRole('button', { name: 'Remove large.png', exact: true }).click();
    const artifactResult = await ui.request({ type: 'artifact.create', topic: 'general', kind: 'note', title: 'Existing chip', content: 'Evidence' });
    const artifact = (artifactResult.value as { artifact: { id: string } }).artifact;
    await form.getByRole('button', { name: 'Attach an artifact', exact: true }).click();
    const search = page.getByRole('combobox', { name: 'Search palette' });
    await search.fill('~Existing chip');
    await page.getByRole('option').filter({ hasText: 'Existing chip' }).click();
    await form.locator('[data-composer-artifact]').waitFor();
    await form.getByRole('button', { name: 'Attach a file', exact: true }).click({ trial: true, timeout: 500 });
    await input.setInputFiles({ name: 'mixed.txt', mimeType: 'text/plain', buffer: Buffer.from('mixed bytes') });
    await form.locator('[data-composer-file]').waitFor();
    await resizePage(page, { width: 390, height: 844 });
    await page.locator('[data-object-id="general"]').click();
    assert.equal(await form.evaluate(node => node.scrollWidth <= node.clientWidth), true, 'file chips fit phone width');
    await field.fill('Plain send');
    await form.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByText('Plain send', { exact: true }).first().waitFor();
    const after = await ui.request({ type: 'topic.history', topic: 'general' });
    const mixed = (after.value as { messages: TopicMessage[] }).messages.find(row => row.text === 'Plain send');
    assert.ok(mixed?.artifacts?.some(row => row.id === artifact.id));
    assert.deepEqual(mixed?.artifacts?.map(row => row.title), ['mixed.txt', 'Existing chip']);
    await input.setInputFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('retry') });
    await form.locator('[data-composer-file]').waitFor();
    await field.fill('Retained caption');
    await page.route('**/upload', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Unavailable"}' }));
    await form.getByRole('button', { name: 'Send', exact: true }).click();
    await form.getByRole('alert').waitFor();
    assert.equal(await field.inputValue(), 'Retained caption');
    assert.match(await form.locator('[data-composer-file]').innerText(), /retry.txt/);
    await page.unroute('**/upload');
  });
});

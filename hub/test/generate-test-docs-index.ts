// Deterministic test-guide index. Drift is advisory; existing link/membership checks remain.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export function renderTestDocIndex(documents: ReadonlyArray<{ name: string; content: string }>): string {
  const rows = [...documents].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0).map(({ name, content }) => {
    const path = /^# (.+\.test\.ts)$/m.exec(content)?.[1];
    if (!path || name !== `${path.replaceAll('/', '-')}.md`) throw new Error(`${name}: test file heading does not match filename`);
    return `| [\`${path}\`](../../../${path}) | [Notes](${name}) |`;
  });
  return '# Test-file guidance\n\nGenerated by `node hub/test/generate-test-docs-index.ts --write`. Add guidance in the matching test document, then regenerate this index.\n\n| Test file | Guidance |\n| --- | --- |\n' + rows.join('\n') + '\n';
}
export function derivedTestDocIndex(folder: URL): string {
  return renderTestDocIndex(readdirSync(folder).filter(name => name !== 'index.md' && name.endsWith('.md')).map(name => ({ name, content: readFileSync(new URL(name, folder), 'utf8') })));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const folder = new URL('../../docs/agents/tests/', import.meta.url);
  const expected = derivedTestDocIndex(folder);
  if (process.argv.includes('--write')) writeFileSync(new URL('index.md', folder), expected);
  else console.log(readFileSync(new URL('index.md', folder), 'utf8') === expected ? 'test guide index: current' : 'test guide index: drift (report only); run node hub/test/generate-test-docs-index.ts --write');
}

test('an upstream answer returns to the actionable asker after its role handover', async t => {
  const root = await tempProject(t);
  const { discovery } = await startDaemon(t, root);
  const roles = join(root, '.cland', 'roles.toml');
  const text = await readFile(roles, 'utf8');
  const section = text.indexOf('[implementer.permissions]');
  // A project may grant its Implementers handover; the pending decision moves with their work.
  await writeFile(roles, text.slice(0, section) + text.slice(section).replace('tools = [', 'tools = ["role.handover", '));
  const ui = await connectUi(t, discovery);
  const coord = await spawnSpoke({ cwd: root, discover: true, name: 'coord', role: 'coordinator', sessionId: 'coord-id' });
  const impl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', role: 'implementer', sessionId: 'impl-id' });
  const next = await spawnSpoke({ cwd: root, discover: true, name: 'next', role: 'implementer', sessionId: 'next-id' });
  for (const s of [coord, impl, next]) t.after(() => s.close());
  await coord.waitForPresence(['coord', 'impl', 'next']);
  await impl.call('send', { topic: 'general', to: ['coordinator'], kind: 'question', text: 'Inherited return?' });
  const history = async () => ((await ui.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages;
  const original = (await history()).find(m => m.text === 'Inherited return?')!;
  const note = { goals_now: 'Continue this item.', work_in_flight: 'Question sent.', open_decisions: 'Inherited return?', waiting_on: 'Coordinator answer.' };
  assert.equal((await impl.call<{ ok: boolean }>('role.handover', { to: 'next', note })).ok, true);
  assert.equal((await coord.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Use the policy.' })).ok, true);
  await next.waitForEvent(e => e.params.meta?.answer_to === original.id);
  const messages = await history();
  assert.equal(messages.find(m => m.id === original.id)!.from, 'impl', 'the original transcript stays historical');
  assert.deepEqual(messages.find(m => m.answerTo === original.id)!.to, ['next']);
});


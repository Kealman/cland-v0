test('an unseen Coordinator successor adopts pending asks before rename and another handover', async t => {
  const root = await tempProject(t);
  const { discovery } = await startDaemon(t, root);
  const ui = await connectUi(t, discovery);
  const coord = await spawnSpoke({ cwd: root, discover: true, name: 'coord', role: 'coordinator', sessionId: 'coord-id' });
  const impl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', role: 'implementer', sessionId: 'impl-id' });
  t.after(() => coord.close()); t.after(() => impl.close());
  await coord.waitForPresence(['coord', 'impl']);
  const history = async () => ((await ui.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages;
  const waitingFor = async () => ((await ui.request({ type: 'topic.list' })).value as { topics: Topic[] }).topics.find(t => t.id === 'general')!.waitingFor;
  const asks: string[] = [];
  for (const text of ['Rename policy?', 'Second handover policy?']) {
    await impl.call('send', { topic: 'general', to: ['coordinator'], kind: 'question', text });
    asks.push((await history()).find(m => m.text === text)!.id);
  }
  assert.equal((await ui.request({ type: 'role.set', session: 'offline-next', role: 'coordinator', move: true })).ok, true);
  assert.deepEqual(await waitingFor(), ['offline-next']);
  const next = await spawnSpoke({ cwd: root, discover: true, name: 'offline-next', assignRole: false, sessionId: 'next-id' });
  t.after(() => next.close());
  await next.waitForPresence(['offline-next', 'impl']);
  assert.equal((await next.call<{ ok: boolean }>('rename', { name: 'renamed-next' })).ok, true);
  assert.deepEqual(await waitingFor(), ['renamed-next']);
  const answer = await next.call<{ ok: boolean }>('ask.answer', { ask: asks[0]!, text: 'Keep compatibility.' });
  assert.equal(answer.ok, true, JSON.stringify(answer));
  await impl.waitForEvent(e => e.params.meta?.answer_to === asks[0]);
  assert.equal((await ui.request({ type: 'role.set', session: 'final-coord', role: 'coordinator', move: true })).ok, true);
  const final = await spawnSpoke({ cwd: root, discover: true, name: 'final-coord', assignRole: false, sessionId: 'final-id' });
  t.after(() => final.close());
  await final.waitForPresence(['final-coord', 'impl']);
  assert.equal((await final.call<{ ok: boolean }>('rename', { name: 'renamed-final' })).ok, true);
  assert.deepEqual(await waitingFor(), ['renamed-final']);
  const human = await final.call<{ ok: boolean; ask: string }>('ask.forward', { ask: asks[1]! });
  assert.equal(human.ok, true, JSON.stringify(human));
  assert.equal((await ui.request({ type: 'topic.answer', ask: human.ask, text: 'Keep compatibility.' })).ok, true);
  assert.equal((await final.call<{ ok: boolean }>('ask.answer', { ask: asks[1]!, text: 'Keep compatibility.' })).ok, true);
  await impl.waitForEvent(e => e.params.meta?.answer_to === asks[1]);
});

test('pending agent asks follow the Coordinator handover durably and return after a human answer', async t => {
  const root = await tempProject(t);
  const first = await startDaemon(t, root);
  const ui = await connectUi(t, first.discovery);
  const coord = await spawnSpoke({ cwd: root, discover: true, name: 'coord', role: 'coordinator', sessionId: 'coord-id' });
  const next = await spawnSpoke({ cwd: root, discover: true, name: 'next', role: 'implementer', sessionId: 'next-id' });
  const impl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', role: 'implementer', sessionId: 'impl-id' });
  for (const s of [coord, next, impl]) t.after(() => s.close());
  await coord.waitForPresence(['coord', 'next', 'impl']);
  await impl.call('send', { topic: 'general', to: ['coordinator'], kind: 'question', text: 'Inherited policy?' });
  const original = ((await ui.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages.find(m => m.text === 'Inherited policy?')!;
  assert.equal((await ui.request({ type: 'role.set', session: 'next', role: 'coordinator', move: true })).ok, true);
  const topics = ((await ui.request({ type: 'topic.list' })).value as { topics: Topic[] }).topics;
  assert.deepEqual(topics.find(t => t.id === 'general')!.waitingFor, ['next']);
  assert.equal((await coord.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Revoked answer' })).ok, false);
  await coord.close(); await next.close(); await impl.close();
  await killDaemon(first.discovery.pid);
  const restarted = await startDaemon(t, root);
  const freshUi = await connectUi(t, restarted.discovery);
  const freshNext = await spawnSpoke({ cwd: root, discover: true, name: 'next', assignRole: false, sessionId: 'next-id' });
  const freshImpl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', assignRole: false, sessionId: 'impl-id' });
  t.after(() => freshNext.close()); t.after(() => freshImpl.close());
  await freshNext.waitForPresence(['next', 'impl']);
  const history = async () => ((await freshUi.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages;
  assert.equal((await history()).find(m => m.id === original.id)!.ask!.to, 'next');
  const human = await freshNext.call<{ ok: boolean; ask: string }>('ask.forward', { ask: original.id });
  assert.equal(human.ok, true, JSON.stringify(human));
  assert.equal((await freshUi.request({ type: 'topic.answer', ask: human.ask, text: 'Keep compatibility.' })).ok, true);
  await freshNext.waitForEvent(e => e.params.meta?.answer_to === human.ask);
  assert.equal((await freshNext.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Keep compatibility.' })).ok, true);
  await freshImpl.waitForEvent(e => e.params.meta?.answer_to === original.id);
  assert.equal((await history()).find(m => m.id === original.id)!.ask!.state, 'answered');
});


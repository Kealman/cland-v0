test('the root-only flat chain survives a daemon restart, returns its answer, and rejects actions by the asker', async t => {
  const root = await tempProject(t);
  const first = await startDaemon(t, root);
  const ui = await connectUi(t, first.discovery);
  const coord = await spawnSpoke({ cwd: root, discover: true, name: 'coord', role: 'coordinator', sessionId: 'coord-id' });
  const impl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', role: 'implementer', sessionId: 'impl-id' });
  t.after(() => coord.close()); t.after(() => impl.close());
  await coord.waitForPresence(['coord', 'impl']);
  await impl.call('send', { topic: 'general', to: ['coordinator'], kind: 'question', text: 'Which flat default?' });
  const original = ((await ui.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages.find(m => m.text === 'Which flat default?')!;
  const human = await coord.call<{ ok: boolean; ask: string }>('ask.forward', { ask: original.id });
  assert.equal(human.ok, true, JSON.stringify(human));
  await coord.close(); await impl.close();
  await killDaemon(first.discovery.pid);
  const restarted = await startDaemon(t, root);
  const freshUi = await connectUi(t, restarted.discovery);
  const freshCoord = await spawnSpoke({ cwd: root, discover: true, name: 'coord', assignRole: false, sessionId: 'coord-id' });
  const freshImpl = await spawnSpoke({ cwd: root, discover: true, name: 'impl', assignRole: false, sessionId: 'impl-id' });
  t.after(() => freshCoord.close()); t.after(() => freshImpl.close());
  await freshCoord.waitForPresence(['coord', 'impl']);
  const history = async () => ((await freshUi.request({ type: 'topic.history', topic: 'general' })).value as { messages: TopicMessage[] }).messages;
  assert.equal((await history()).find(m => m.id === original.id)?.ask?.forwarded, human.ask);
  assert.equal((await freshImpl.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Impersonation' })).ok, false);
  assert.equal((await freshUi.request({ type: 'topic.answer', ask: human.ask, text: 'Use the flat default.' })).ok, true);
  const answer = await freshCoord.call<{ ok: boolean; message: TopicMessage }>('ask.answer', { ask: original.id, text: 'Use the flat default.' });
  assert.equal(answer.ok, true, JSON.stringify(answer));
  assert.equal(answer.message.answerTo, original.id);
  await freshImpl.waitForEvent(e => e.params.meta?.answer_to === original.id);
  assert.equal((await history()).find(m => m.id === original.id)?.ask?.state, 'answered');
  assert.equal((await freshCoord.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Duplicate' })).ok, false);
  assert.equal((await history()).filter(m => m.answerTo === original.id).length, 1);
});

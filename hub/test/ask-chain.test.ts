  assert.equal(releaseForward.ok, true, JSON.stringify(releaseForward));
  assert.deepEqual((await messages()).find(m => m.id === releaseForward.ask)?.to, ['coord']);
  const human = await coord.call<{ ok: boolean; ask: string }>('ask.forward', { ask: releaseForward.ask });
  assert.equal(human.ok, true, JSON.stringify(human));
  assert.deepEqual((await messages()).filter(m => m.ask).map(m => m.text), [text, text, text, text]);
  assert.equal((await coord.call<{ ok: boolean }>('ask.forward', { ask: releaseForward.ask })).ok, false, 'a repeated forward cannot create another human ask');
  await ui.request({ type: 'topic.close', topic: topic.id });
  assert.deepEqual((await messages()).filter(m => m.ask).map(m => m.ask!.state), ['cancelled', 'cancelled', 'cancelled', 'cancelled']);
  assert.equal((await leads[1]!.spoke.call<{ ok: boolean }>('ask.answer', { ask: original.id, text: 'Too late' })).ok, false);
